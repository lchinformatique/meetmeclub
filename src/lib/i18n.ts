export type TranslationKey = keyof typeof DICTIONARY.fr;

export function getLanguage(): SupportedLanguage {
  if (typeof window === "undefined") return DEFAULT_LANGUAGE;
  const stored = localStorage.getItem("mmclub_lang") as SupportedLanguage;
  if (stored && DICTIONARY[stored]) return stored;

  // Auto-detect browser language
  const browserLang = (navigator.language || navigator.languages?.[0] || "fr").slice(0, 2).toLowerCase();
  if (browserLang in DICTIONARY) {
    return browserLang as SupportedLanguage;
  }
  return DEFAULT_LANGUAGE;
}

export function setLanguage(lang: SupportedLanguage) {
  if (typeof window === "undefined") return;
  localStorage.setItem("mmclub_lang", lang);
  document.cookie = `mmclub_lang=${lang}; path=/; max-age=31536000; SameSite=Lax`;
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";
  window.dispatchEvent(new CustomEvent("mmclub_lang_changed", { detail: { lang } }));
}

export function t(key: TranslationKey, lang?: SupportedLanguage): string {
  const activeLang = lang || (typeof window !== "undefined" ? getLanguage() : DEFAULT_LANGUAGE);
  const dict = DICTIONARY[activeLang] || DICTIONARY.fr;
  return (dict as any)[key] || (DICTIONARY.fr as any)[key] || key;
}
